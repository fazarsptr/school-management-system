    private void loadGuruKeComboBox() {
    try {
        java.sql.Connection conn = com.mtsarridho.config.KoneksiDatabase.getKoneksi();
        java.sql.Statement stmt = conn.createStatement();
        java.sql.ResultSet rs = stmt.executeQuery("SELECT nik, nama FROM tb_guru");
        
        walikelas.removeAllItems();
        walikelas.addItem(new GuruItem("", "--- PILIH ---"));
        
        while (rs.next()) {
            String nik = rs.getString("nik");
            String nama = rs.getString("nama");
            walikelas.addItem(new GuruItem(nik, nama));
        }

        rs.close();
        stmt.close();
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal memuat data wali kelas: " + e.getMessage());
    }
}
    
    private void pilihGuruDiComboBox(String namaGuru) {
    for (int i = 0; i < walikelas.getItemCount(); i++) {
        GuruItem item = walikelas.getItemAt(i);
        if (item.getNama().equals(namaGuru)) {
            walikelas.setSelectedIndex(i);
            break;
        }
    }
    }

