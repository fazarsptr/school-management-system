    private void simpaneditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpaneditActionPerformed
    String newTingkatKelas = tingkatkelas.getSelectedItem().toString();
    String newNamaRombel = namarombel.getSelectedItem().toString();
    String newWaliKelas = walikelas.getSelectedItem().toString();
    String newTahunAjaran = tahunajaran.getText();

    if (newNamaRombel.isEmpty() || newWaliKelas.equals("--- PILIH ---") ||
        newTingkatKelas.equals("--- PILIH ---") || newTahunAjaran.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Semua field harus diisi!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        java.sql.Connection conn = com.mtsarridho.config.KoneksiDatabase.getKoneksi();

        String nikGuru = "";
        String sqlGuru = "SELECT nik FROM tb_guru WHERE nama = ?";
        java.sql.PreparedStatement pstGuru = conn.prepareStatement(sqlGuru);
        pstGuru.setString(1, newWaliKelas);
        java.sql.ResultSet rs = pstGuru.executeQuery();
        if (rs.next()) {
            nikGuru = rs.getString("nik");
        } else {
            JOptionPane.showMessageDialog(this, "Wali kelas tidak ditemukan di database!");
            return;
        }

        String sql = "UPDATE tb_rombel SET nama_rombel = ?, wali_kelas = ?, tingkat_kelas = ?, tahun_ajaran = ? WHERE nama_rombel = ?";
        java.sql.PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, newNamaRombel);  
        pst.setString(2, nikGuru);        
        pst.setString(3, newTingkatKelas);
        pst.setString(4, newTahunAjaran);
        pst.setString(5, oldNamaRombel); 


        int result = pst.executeUpdate();
        if (result > 0) {
            JOptionPane.showMessageDialog(this, "Data berhasil diedit.");
            tableModel.setValueAt(newNamaRombel, rowIndex, 1);   
            tableModel.setValueAt(newWaliKelas, rowIndex, 2);      
            tableModel.setValueAt(newTingkatKelas, rowIndex, 3);   
            tableModel.setValueAt(newTahunAjaran, rowIndex, 4);    

        } else {
            JOptionPane.showMessageDialog(this, "Gagal mengedit data rombel!", "Error", JOptionPane.ERROR_MESSAGE);
        }

        pst.close();
        rs.close();
        pstGuru.close();
        // conn.close(); 

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error saat update database: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_simpaneditActionPerformed

