    private void rSMaterialButtonRectangle1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rSMaterialButtonRectangle1ActionPerformed
        GuruItem selectedGuru = (GuruItem) jComboBox1.getSelectedItem();

        if (selectedGuru != null) {
            String nikGuru = selectedGuru.getNik();         // dari combo box
            String namaGuru = selectedGuru.getNama();       // dari combo box
            String mapel = jComboBox3.getSelectedItem().toString();
            String nama_kelas = jComboBox2.getSelectedItem().toString();// hadir/tidak hadir
            

            try {
                Connection conn = KoneksiDatabase.getKoneksi();

                // CEK APAKAH DATA SUDAH ADA
                String cekSql = "SELECT COUNT(*) FROM tb_mapel WHERE nik_guru = ? AND kelas = ?";
                PreparedStatement cekStmt = conn.prepareStatement(cekSql);
                cekStmt.setString(1, nikGuru);
                cekStmt.setString(2, nama_kelas);
                ResultSet rs = cekStmt.executeQuery();
                rs.next();
                int count = rs.getInt(1);

                if (count > 0) {
                    JOptionPane.showMessageDialog(this, "Guru ini sudah mengajar di tingkat tersebut");
                } else {
                    // INSERT DATA
                    String sql = "INSERT INTO tb_mapel (nik_guru, nama_mapel, kelas) VALUES (?, ?, ?)";
                    PreparedStatement stmt = conn.prepareStatement(sql);
                    stmt.setString(1, nikGuru);
                    stmt.setString(2, mapel);
                    stmt.setString(3, nama_kelas);
                    
                    stmt.executeUpdate();

                    JOptionPane.showMessageDialog(this, "Data mengajar berhasil disimpan!");
                    if (parentForm != null) {
                        parentForm.tampilkanDataGuru();
                    }
                }

            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage());
            }
        } else {
            JOptionPane.showMessageDialog(this, "Silakan pilih guru terlebih dahulu.");
        }
    }//GEN-LAST:event_rSMaterialButtonRectangle1ActionPerformed

